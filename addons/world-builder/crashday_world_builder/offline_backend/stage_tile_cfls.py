"""Prepare a private, OFFLINE native CFL/P3D tile staging tree from an audited
Tile Splitter manifest. This is NOT a .trk writer or an engine-tested world.

Only writes to a fresh directory under this project's ignored out/ folder.
The user-authored models and exact geometry are never clipped to CFL footprints.
Python 3.7+, standard library only; requires adjacent validate_p3d.py.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import shutil

from .validate_p3d import validate_tile_manifest
from .source_tga_stage import verify_source_tga_manifest
from .source_tex_stage import policy_descriptors, render_preset
from .source_tile_preview_stage import validate_preview_manifest, file_sha

CELL_METERS = 20.0
EPSILON = 0.0002
MAX_GRID_SLOTS = 32768


class StageError(ValueError):
    pass


def _numeric(values, count, name):
    if (not isinstance(values, list) or len(values) != count or
            any(type(value) not in (float, int) or not math.isfinite(value)
                for value in values)):
        raise StageError("Missing or nonfinite {} in tile manifest".format(name))
    return [float(v) for v in values]


def _integer_cells(length, name, macro_layout=False):
    count = round(length / CELL_METERS)
    if macro_layout:
        from .author_trk_offline import MAX_AXIS
        if not 1 <= count <= MAX_AXIS or abs(count * CELL_METERS - length) > EPSILON:
            raise StageError("Macro physical bounds must be bounded multiples of 20m: " + name)
        return int(count)
    if count not in (1, 2) or abs(count * CELL_METERS - length) > EPSILON:
        raise StageError("{} must be 20m or 40m for the current CFL stage (got {})".format(name, length))
    return int(count)


def _grid_index(value, anchor):
    delta = (value - anchor) / CELL_METERS
    result = round(delta)
    if result < 0 or result > MAX_GRID_SLOTS or abs(delta - result) > EPSILON / CELL_METERS:
        raise StageError("Tile bounds are not aligned to the common 20m authoring grid")
    return int(result)


def _native_cfl(model, width, depth):
    # Preserve native Redline CFL line framing. Real stock files use CRLF,
    # the full vegetation separator, and an empty line before NO_VEGETATION.
    # The old LF-only shorthand parsed in our Python tests but was rejected
    # by the original game during Mod Testing startup.
    # The sixth native CFL line is "Autolist in track editor". For
    # world-specific authored tiles use 0: the track references the CFL
    # directly, and we must not clutter or depend on the editor palette.
    # No synthetic editor .cat is generated by this world-stage pipeline.
    # User-specific ground/checkpoint/AI settings remain provisional.
    fields = [
        "Crashday-FieldObject-File",
        "-", model, "{} {}".format(width, depth),
        "GROUND_FLAT", "0", "NONE", "0.0", "1", "0", "0",
        "default", "STOP", "",
        "------------------- VEGETATION -------------------",
        "", "NO_VEGETATION", "",
    ]
    return ("\r\n".join(fields) + "\r\n").encode("ascii")


def _validate_macro_previews(manifest_path, preview_manifest, entries, plan):
    """Bind a native-anchor crop sidecar to the exact physical P3D source.

    The normal preview validator remains responsible for dimensions, paths,
    raster framing and file hashes. This adapter does not infer pixel content
    or resize geometry; a renderer must actually produce the declared crop.
    """
    from .native_tile_preview import tile_preview_path
    from .source_tile_preview_stage import MAX_MANIFEST_BYTES
    pieces = {p["p3d"]: p for p in plan["pieces"]}
    projected = [
        dict(entry, logical_tile_bounds_xy=pieces[entry["file"]]["logical_bounds_world_xy"])
        for entry in entries
    ]
    try:
        checked = validate_preview_manifest(manifest_path, preview_manifest, projected)
        path = Path(preview_manifest)
        if path.is_symlink() or path.stat().st_size > MAX_MANIFEST_BYTES:
            raise StageError("Unsafe macro preview manifest")
        with path.open("rb") as handle:
            raw = handle.read(MAX_MANIFEST_BYTES + 1)
        if (len(raw) > MAX_MANIFEST_BYTES or
                hashlib.sha256(raw).hexdigest() != checked["manifest_sha256"]):
            raise StageError("Macro preview manifest changed during validation")
        records = json.loads(raw.decode("utf-8"))["tiles"]
        by_path = {tile_preview_path(p["cfl"]): p for p in pieces.values()}
        for record in checked["records"]:
            piece = by_path[record["path"]]
            source = records[record["path"]]
            if (source.get("crop_contract") != "centered-native-anchor-v2" or
                    not str(source.get("render_contract", "")).endswith("-exact-fit") or
                    source.get("p3d_sha256") != piece["p3d_sha256"] or
                    source.get("p3d_manifest_sha256") != plan["input_manifest_sha256"]):
                raise StageError("Macro preview crop/P3D binding missing or mismatched")
            for name, expected in (
                    ("crop_bounds_world_xy", piece["logical_bounds_world_xy"]),
                    ("physical_bounds_world_xy", piece["physical_bounds_world_xy"])):
                supplied = _numeric(source.get(name), 4, name)
                if any(abs(a-b) > EPSILON for a,b in zip(supplied, expected)):
                    raise StageError("Macro preview bounds differ from planned native anchor: " + name)
                record[name] = supplied
            record.update(crop_contract=source["crop_contract"],
                          p3d_sha256=source["p3d_sha256"],
                          p3d_manifest_sha256=source["p3d_manifest_sha256"])
        return checked
    except (OSError, ValueError, KeyError, TypeError) as exc:
        raise StageError("Macro preview validation failed: " + str(exc)) from exc


def plan_tiles(manifest_path, texture_manifest=None, tex_policy=None,
               tile_preview_manifest=None, macro_layout=False):
    """Validate source P3D bytes first; never substitute geometry for metadata.

    The original v1 manifest omitted logical cell bounds. Such files can still
    be checked by P3D Validator, but cannot safely define a CFL footprint:
    an oversized authored P3D may have a 20m nominal footprint or vice versa.
    Explicit macro_layout interprets the exported logical_tile_bounds_xy as
    physical authoring rectangles, preserving their centers and model bytes.
    Only centered 1/2-cell logical CFL anchors are generated. It requires
    complete physical coverage and an explicit native void pair at TRK build.
    """
    if type(macro_layout) is not bool:
        raise StageError("Macro layout mode must be explicitly true or false")
    if tex_policy is not None and texture_manifest is None:
        raise StageError("Explicit TEX preset policy requires genuine source TGA manifest")
    path = Path(manifest_path)
    checked = validate_tile_manifest(path)
    if not checked["ok"]:
        detail = checked["errors"] + [
            "{}: {}".format(a["file"], error)
            for a in checked["assets"] for error in a["errors"]]
        raise StageError("Tile manifest/P3D validation failed: " + "; ".join(detail[:5]))
    raw = path.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != checked["manifest_sha256"]:
        raise StageError("Manifest changed since validation")
    manifest = json.loads(raw.decode("utf-8"))
    entries = manifest["p3d_files"]
    bounds = []
    for entry in entries:
        value = _numeric(entry.get("logical_tile_bounds_xy"), 4, "logical_tile_bounds_xy")
        if value[1] <= value[0] or value[3] <= value[2]:
            raise StageError("Reversed or empty logical tile bounds for " + entry["file"])
        origin = _numeric(entry["tile_origin_world_xy"], 2, "tile_origin_world_xy")
        if (abs((value[0] + value[1]) / 2 - origin[0]) > EPSILON or
                abs((value[2] + value[3]) / 2 - origin[1]) > EPSILON):
            raise StageError("Tile origin differs from authored logical bounds for " + entry["file"])
        width = _integer_cells(value[1] - value[0], "CFL width", macro_layout)
        depth = _integer_cells(value[3] - value[2], "CFL depth", macro_layout)
        bounds.append((entry, value, width, depth))
    anchor_x = min(row[1][0] for row in bounds)
    anchor_y = min(row[1][2] for row in bounds)
    macro = None
    macro_pieces = {}
    if macro_layout:
        from .macro_native_layout import MacroLayoutError, plan_centered_macro_anchors
        regions = []
        for entry, extent, width, depth in bounds:
            regions.append({"cfl": entry["file"][:-4] + ".cfl",
                            "role": "remainder",
                            "cell_origin": [_grid_index(extent[0], anchor_x),
                                            _grid_index(extent[2], anchor_y)],
                            "cell_dimensions": [width, depth]})
        grid = [max(r["cell_origin"][i] + r["cell_dimensions"][i]
                    for r in regions) for i in range(2)]
        try:
            macro = plan_centered_macro_anchors(grid, [anchor_x, anchor_y], regions)
        except MacroLayoutError as exc:
            raise StageError(str(exc)) from exc
        macro_pieces = {p["cfl"]: p for p in macro["pieces"]}
    occupied = set()
    pieces = []
    cfl_data = {}
    for entry, extent, width, depth in sorted(bounds, key=lambda row: row[0]["file"]):
        cfl_name = entry["file"][:-4] + ".cfl"
        anchor = macro_pieces.get(cfl_name)
        if anchor is not None:
            x, y = anchor["logical_cell_origin"]
            width, depth = anchor["logical_cell_footprint"]
            extent = anchor["logical_bounds_world_xy"]
        else:
            x = _grid_index(extent[0], anchor_x)
            y = _grid_index(extent[2], anchor_y)
        for dx in range(width):
            for dy in range(depth):
                cell = (x + dx, y + dy)
                if cell in occupied:
                    raise StageError("Overlapping authored CFL cells at {}".format(cell))
                occupied.add(cell)
                if len(occupied) > MAX_GRID_SLOTS:
                    raise StageError("Too many occupied logical 20m cells")
        cfl_data[cfl_name] = _native_cfl(entry["file"], width, depth)
        pieces.append({
            "tile_key": entry["key"], "p3d": entry["file"],
            "p3d_sha256": entry["sha256"], "cfl": cfl_name,
            "cfl_sha256": hashlib.sha256(cfl_data[cfl_name]).hexdigest(),
            "logical_bounds_world_xy": extent,
            # Retain the actual Blender world Z centre independently from the
            # nominal CFL XY footprint. Flat-height TRK drafts otherwise
            # cannot prove the model's relative vertical placement.
            "source_main_world_center_xyz": _numeric(
                entry.get("main_world_center"), 3, "main_world_center"),
            "source_floor_z": entry.get("floor_z"),
            "logical_cell_origin": [x, y],
            "logical_cell_footprint": [width, depth],
        })
        if anchor is not None:
            for key in ("physical_cell_origin", "physical_cell_dimensions",
                        "physical_bounds_world_xy", "required_model_origin_world_xy"):
                pieces[-1][key] = anchor[key]
    plan = {
        "schema": "micas-crashday-offline-tile-stage/v0",
        "engine_validation": "NOT TESTED: native CFL fields provisional; no TRK or gameplay output",
        "input_manifest_sha256": digest, "grid_origin_world_xy": [anchor_x, anchor_y],
        "cell_size_meters": 20, "occupied_cell_count": len(occupied),
        "tile_count": len(pieces), "pieces": pieces,
        "unresolved": ["CFL game-load/collision", "world TRK/heightmap",
                       "native texture dependencies", "AI navigation and gameplay"],
    }
    if macro is not None:
        for key in ("grid_dimensions_cells", "physical_cell_count", "void_cell_count", "void_cells"):
            plan[key] = macro[key]
        plan["macro_layout"] = True
        plan["unresolved"].append("Macro native void/oversized collision and preview semantics unverified")
    if texture_manifest is not None:
        textures = verify_source_tga_manifest(manifest_path, texture_manifest)
        plan["source_textures"] = textures["records"]
        plan["source_texture_manifest_sha256"] = textures["manifest_sha256"]
        plan["source_native_texture_refs"] = textures["native_refs"]
        plan["unresolved_source_texture_refs"] = textures["unresolved"]
        plan["source_texture_bytes"] = textures["total_bytes"]
        if textures["unresolved"]:
            plan["unresolved"].append("Missing genuine source images for {} P3D texture IDs".format(
                len(textures["unresolved"])))
        if tex_policy is None:
            plan["unresolved"].append("Native game .tex descriptors not authored")
        else:
            tex = policy_descriptors(texture_manifest, textures, tex_policy)
            plan["native_tex_descriptors"] = tex["records"]
            plan["native_tex_policy_sha256"] = tex["policy_sha256"]
            plan["native_tex_source_manifest_sha256"] = tex["source_tga_manifest_sha256"]
            plan["unresolved_native_tex_refs"] = sorted(
                set(textures["native_refs"]) - {record["texture"] for record in tex["records"]})
            if plan["unresolved_native_tex_refs"]:
                plan["unresolved"].append("No explicitly chosen TEX preset for {} native references".format(
                    len(plan["unresolved_native_tex_refs"])))
            plan["unresolved"].append("EXPERIMENTAL .tex presets: game shader and material behaviour NOT tested")
    if tile_preview_manifest is not None:
        if macro_layout:
            verified_previews = _validate_macro_previews(
                manifest_path, tile_preview_manifest, entries, plan)
        else:
            verified_previews = validate_preview_manifest(
                manifest_path, tile_preview_manifest, entries)
        plan["native_tile_previews"] = verified_previews["records"]
        plan["native_tile_preview_manifest_sha256"] = verified_previews["manifest_sha256"]
        plan["native_tile_preview_bytes"] = verified_previews["total_bytes"]
        plan["unresolved"].append(
            "Preview pixel appearance in original Crashday editor NOT game-verified")
    return plan, cfl_data


def stage_tiles(manifest_path, label, workspace=None, texture_manifest=None,
                tex_policy=None, tile_preview_manifest=None, macro_layout=False):
    """Create an entirely new private staging tree; never touch Steam/game paths."""
    if not isinstance(label, str) or not re.fullmatch(r"[A-Za-z0-9_-]{1,64}", label):
        raise StageError("Stage label must be a short ASCII basename")
    base = Path(workspace) if workspace is not None else Path(__file__).resolve().parents[1] / "out"
    if not base.is_dir() or base.is_symlink():
        raise StageError("Private output base is missing or redirected")
    if macro_layout:
        from .author_trk_offline import _private_output_root
        base = _private_output_root(base)
    target = base / label
    if target.exists() or target.is_symlink():
        raise StageError("Refusing to overwrite an existing stage")
    plan, cfl_data = plan_tiles(
        manifest_path, texture_manifest=texture_manifest, tex_policy=tex_policy,
        tile_preview_manifest=tile_preview_manifest, macro_layout=macro_layout)
    manifest_parent = Path(manifest_path).resolve(strict=True).parent
    created = False
    try:
        # The target may have appeared since the preflight. A failed mkdir
        # must never trigger cleanup of another creator's new directory.
        target.mkdir()
        created = True
        # Native stock Redline packages split tile definitions and model
        # payloads into distinct directories. Do not put P3Ds beside CFLs.
        tiles = target / "content" / "tiles"
        models = target / "content" / "models"
        tiles.mkdir(parents=True)
        models.mkdir(parents=True)
        for piece in plan["pieces"]:
            data = (manifest_parent / piece["p3d"]).read_bytes()
            if hashlib.sha256(data).hexdigest() != piece["p3d_sha256"]:
                raise StageError("P3D changed after source validation: " + piece["p3d"])
            (models / piece["p3d"]).write_bytes(data)
            (tiles / piece["cfl"]).write_bytes(cfl_data[piece["cfl"]])
        # Copy only exact hash-verified, native-dimension per-CFL preview images.
        # Each picture is a separate palette asset; no P3D geometry is cropped.
        if tile_preview_manifest is not None:
            if (Path(tile_preview_manifest).is_symlink() or
                    file_sha(tile_preview_manifest) != plan["native_tile_preview_manifest_sha256"]):
                raise StageError("Preview manifest changed during staging")
            for item in plan["native_tile_previews"]:
                src = manifest_parent.joinpath(*item["path"].split("/"))
                dst = target.joinpath(*item["path"].split("/"))
                if src.is_symlink() or not src.is_file() or file_sha(src) != item["sha256"]:
                    raise StageError("Native preview image changed during staging: " + item["path"])
                dst.parent.mkdir(parents=True, exist_ok=True)
                with src.open("rb") as reader, dst.open("xb") as writer:
                    shutil.copyfileobj(reader, writer, length=1024 * 1024)
                if dst.stat().st_size != item["bytes"] or file_sha(dst) != item["sha256"]:
                    raise StageError("Native preview staging changed source bytes: " + item["path"])
        if texture_manifest is not None and plan["source_textures"]:
            from .source_tga_stage import _hash_file
            textures = target / "content" / "textures"
            # Native preview TGAs may already have created textures/pictures/tiles.
            # Reuse that parent directory; each actual source .tga still uses xb.
            textures.mkdir(parents=True, exist_ok=True)
            for row in plan["source_textures"]:
                src = manifest_parent / "textures" / row["file"]
                dst = textures / row["file"]
                # Re-check after preflight so a changed original is never
                # silently copied under a stale approved checksum.
                if src.is_symlink() or not src.is_file() or _hash_file(src) != row["sha256"]:
                    raise StageError("Source TGA changed after preflight: " + row["file"])
                with src.open("rb") as i, dst.open("xb") as o:
                    shutil.copyfileobj(i, o, length=1024 * 1024)
                if dst.stat().st_size != row["bytes"] or _hash_file(dst) != row["sha256"]:
                    raise StageError("Copied source TGA did not preserve exact bytes: " + row["file"])
        if tex_policy is not None:
            policy_file = Path(tex_policy)
            if (policy_file.is_symlink() or not policy_file.is_file() or
                    hashlib.sha256(policy_file.read_bytes()).hexdigest() !=
                    plan["native_tex_policy_sha256"]):
                raise StageError("Explicit TEX policy changed since validated preflight")
            texture_dir = target / "content" / "textures"
            texture_dir.mkdir(parents=True, exist_ok=True)
            for row in plan["native_tex_descriptors"]:
                content = render_preset(row["preset"])
                if hashlib.sha256(content).hexdigest() != row["sha256"]:
                    raise StageError("Generated native TEX differs from approved preset")
                dst = texture_dir / row["file"]
                dst.write_bytes(content)
                if dst.read_bytes() != content:
                    raise StageError("Native TEX stage verification failed")
        (target / "WORLD_STAGE_README.txt").write_text(
            "PRIVATE OFFLINE AUTHORING STAGE. NOT VERIFIED IN CRASHDAY.\n"
            "The generated CFL uses explicit 20m/40m logical footprints and\n"
            "provisional GROUND_FLAT/STOP/no-vegetation settings.\n"
            "P3D mesh/collision extents are unchanged. Optional source TGA\n"
            "images are copied only with verified manifest/hash provenance.\n"
            "Optional explicitly selected source-grounded TEX presets remain\n"
            "EXPERIMENTAL; no game shader/placement/collision/AI validation.\n"
            "Terrain remains flat and independent of 3D model positions.\n",
            encoding="ascii")
        (target / "world_tile_stage.json").write_text(
            json.dumps(plan, sort_keys=True, indent=2, allow_nan=False) + "\n",
            encoding="ascii")
    except Exception:
        # Only remove a stage directory this invocation ACTUALLY created.
        # The previous target-exists preflight alone is not an ownership
        # guarantee if another process creates that path before mkdir.
        if created and target.is_dir() and not target.is_symlink():
            shutil.rmtree(str(target))
        raise
    return target, plan


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--tile-manifest", required=True)
    p.add_argument("--texture-manifest", help="Optional Tile Splitter source TGA manifest beside tile P3Ds")
    p.add_argument("--tex-policy", help="Optional owner-explicit, hash-bound .tex preset JSON beside TGA manifest")
    p.add_argument("--tile-preview-manifest", help="Optional Blender-rendered native per-CFL preview manifest")
    p.add_argument("--macro-layout", action="store_true",
                   help="Explicitly interpret source tile bounds as physical macro rectangles; native void pair required later")
    p.add_argument("--stage-label", default="world_tile_stage")
    p.add_argument("--write", action="store_true", help="Write only into a NEW private out/<stage-label> directory")
    p.add_argument("--json", action="store_true")
    args = p.parse_args(argv)
    try:
        if args.write:
            target, plan = stage_tiles(args.tile_manifest, args.stage_label,
                                       texture_manifest=args.texture_manifest,
                                       tex_policy=args.tex_policy,
                                       tile_preview_manifest=args.tile_preview_manifest,
                                       macro_layout=args.macro_layout)
            plan["private_stage_directory"] = str(target)
        else:
            plan, _ = plan_tiles(args.tile_manifest, texture_manifest=args.texture_manifest,
                                 tex_policy=args.tex_policy,
                                 tile_preview_manifest=args.tile_preview_manifest,
                                 macro_layout=args.macro_layout)
        if args.json:
            print(json.dumps(plan, indent=2, sort_keys=True, allow_nan=False))
        else:
            print("{}: {} CFL/P3D authoring pairs, {} occupied 20m cells (NO game validation)".format(
                "STAGED" if args.write else "DRY RUN",
                plan["tile_count"], plan["occupied_cell_count"]))
        return 0
    except (OSError, ValueError) as e:
        print("INVALID offline world stage: " + str(e))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
